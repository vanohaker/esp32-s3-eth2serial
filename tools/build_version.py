"""Git build identity, recomputed on every build (including incremental builds)."""
import argparse
import json
from pathlib import Path
import re
import subprocess


# SemVer 2.0.0 with the project's mandatory v prefix.
NUMBER = r"(?:0|[1-9][0-9]*)"
PRE = rf"(?:{NUMBER}|[0-9]*[A-Za-z-][0-9A-Za-z-]*)"
TAG = re.compile(rf"v{NUMBER}\.{NUMBER}\.{NUMBER}(?:-{PRE}(?:\.{PRE})*)?"
                 r"(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?")


def version(repo):
    def git(*args):
        return subprocess.check_output(["git", "-C", str(repo), *args], text=True).strip()

    sha = git("rev-parse", "--short=7", "HEAD")
    branch = git("branch", "--show-current")
    tags = [tag for tag in git("tag", "--points-at", "HEAD").splitlines() if TAG.fullmatch(tag)]
    dirty = bool(git("status", "--porcelain", "--untracked-files=normal"))
    if tags and not dirty:
        if len(tags) != 1:
            raise ValueError("HEAD has several SemVer tags; leave one unambiguous release tag")
        return tags[0]
    if not branch:
        raise ValueError("Build from a branch or a clean checkout of a vMAJOR.MINOR.PATCH tag")
    return f"{branch}-{sha}" + ("-dirty" if dirty else "")


def idf_version(value):
    # The SDK descriptor has 31 bytes and CMake passes its initial value through
    # compiler definitions. Keep it ASCII-safe; the web UI has the full name.
    return re.sub(r"[^A-Za-z0-9._+/-]", "_", value)[:31]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--header", type=Path)
    parser.add_argument("--idf-version", action="store_true")
    args = parser.parse_args()
    try:
        value = version(args.repo)
    except (subprocess.CalledProcessError, ValueError) as error:
        parser.exit(1, f"Build version: {error}\n")
    if args.header:
        content = ("// Generated by tools/build_version.py. Do not edit.\n#pragma once\n"
                   f"#define KNIFE_BUILD_VERSION {json.dumps(value, ensure_ascii=False)}\n"
                   "#ifdef KNIFE_OVERRIDE_APP_VERSION\n#undef PROJECT_VER\n"
                   f"#define PROJECT_VER {json.dumps(idf_version(value), ensure_ascii=False)}\n"
                   "#endif\n")
        args.header.parent.mkdir(parents=True, exist_ok=True)
        if not args.header.exists() or args.header.read_text() != content:
            args.header.write_text(content)
            print(f"Build version: {value}")
    else:
        print(idf_version(value) if args.idf_version else value)


if __name__ == "__main__":
    main()
